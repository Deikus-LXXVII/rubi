package main

import (
	"context"
	"errors"
	"fmt"
	"net"
	"os"
	"os/signal"
	"strconv"
	"strings"
	"syscall"

	"github.com/Deikus-LXXVII/rubi/internal/agentbridge"
	"github.com/Deikus-LXXVII/rubi/internal/agentsandbox"
)

func serveOpenCode(ctx context.Context, l agentsandbox.Launch) (int, error) {
	// T3 v2 supplies OPENCODE_PASSWORD; v1 supplies OPENCODE_SERVER_PASSWORD
	// only when configured. Never substitute an unauthenticated v1 endpoint.
	password := os.Getenv("OPENCODE_PASSWORD")
	envKey := "OPENCODE_PASSWORD"
	if password == "" {
		password = os.Getenv("OPENCODE_SERVER_PASSWORD")
		envKey = "OPENCODE_SERVER_PASSWORD"
	}
	if len(password) < 32 {
		return 125, errors.New("OpenCode sandbox bridge requires a T3 server password of at least 32 characters (v1: configure serverPassword; v2: generated by T3)")
	}
	credentials, err := agentbridge.Credentials(l.Policy, l.CredentialsFile)
	if err != nil {
		return 125, err
	}
	credentials[envKey] = password
	state, err := agentbridge.StateEnvironment(l.Policy.Login)
	if err != nil {
		return 125, err
	}
	for key, value := range state {
		credentials[key] = value
	}
	const port = 37173
	args := []string{l.CLI, "serve"}
	for i := 1; i < len(l.Args); i++ {
		a := l.Args[i]
		if a == "--hostname" || a == "--port" {
			i++
			continue
		}
		if strings.HasPrefix(a, "--hostname=") || strings.HasPrefix(a, "--port=") {
			continue
		}
		args = append(args, a)
	}
	args = append(args, "--hostname=127.0.0.1", "--port="+strconv.Itoa(port))
	relay, err := os.Executable()
	if err != nil {
		return 125, err
	}
	life, stop := signal.NotifyContext(ctx, os.Interrupt, syscall.SIGTERM)
	defer stop()
	checkPath := "/api/info"
	if envKey == "OPENCODE_SERVER_PASSWORD" {
		checkPath = "/global/health"
	}
	p, _, err := agentbridge.Start(life, l, relay, agentbridge.Bootstrap{Command: args, Environment: credentials, Port: port, CheckPath: checkPath, CheckUser: "opencode", CheckPassword: password})
	if err != nil {
		return 125, err
	}
	defer p.Close()
	server, err := agentbridge.Frontend(p, port, password)
	if err != nil {
		return 125, err
	}
	listener, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return 125, errors.New("OpenCode bridge cannot bind its authenticated endpoint")
	}
	defer server.Close()
	died := make(chan error, 1)
	go func() { died <- server.Serve(listener) }()
	// Exactly the discovery line T3 understands; no credentials, provider output
	// or inner control data may reach the server's captured diagnostic streams.
	fmt.Fprintf(os.Stdout, "server listening on http://%s\n", listener.Addr())
	select {
	case <-life.Done():
		return 0, nil
	case <-p.Done():
		return 125, errors.New("sandboxed OpenCode exited")
	case <-died:
		return 125, errors.New("OpenCode bridge stopped")
	}
}
